import { expect, test } from '@playwright/test';

test('shared garden cards and plots follow current capabilities', async ({ page, request }) => {
  const base = `${test.info().project.use.baseURL}/api/v1`;
  const stamp = Date.now();
  const ownerResponse = await request.post(`${base}/auth/register`, { data: { username: `owner${stamp}`, email: `owner${stamp}@example.com`, password: 'test-password' } });
  expect(ownerResponse.status()).toBe(201);
  const owner = await ownerResponse.json();
  const viewerResponse = await request.post(`${base}/auth/register`, { data: { username: `guest${stamp}`, email: `guest${stamp}@example.com`, password: 'test-password' } });
  expect(viewerResponse.status()).toBe(201);
  const viewer = await viewerResponse.json();
  const headers = { Authorization: `Bearer ${owner.token}` };
  const created = await request.post(`${base}/gardens`, { headers, data: { name: 'Shared Patch' } });
  expect(created.status()).toBe(201);
  const { garden } = await created.json();
  const catalog = await request.get(`${base}/plants`);
  const { plant_types } = await catalog.json();
  const seed = plant_types.find((plant: { name: string }) => plant.name === 'Lettuce');
  const purchase = await request.post(`${base}/store/buy`, { headers, data: { plant_type_id: seed.id, quantity: 1 } });
  expect(purchase.ok()).toBe(true);
  const planted = await request.post(`${base}/gardens/${garden.id}/plants`, { headers, data: { plant_type_id: seed.id, position: 0 } });
  expect(planted.status()).toBe(201);
  const linkResponse = await request.post(`${base}/garden-shares/access-links`, { headers, data: { garden_id: garden.id, permissions: ['view'] } });
  expect(linkResponse.status()).toBe(201);
  const { access_link } = await linkResponse.json();
  const joined = await request.post(`${base}/garden-shares/join`, { headers: { Authorization: `Bearer ${viewer.token}` }, data: { token: access_link.token } });
  expect(joined.ok()).toBe(true);
  await expect.poll(async () => {
    const response = await request.get(`${base}/gardens/${garden.id}`, { headers });
    return (await response.json()).garden.plants[0].stage;
  }, { timeout: 15_000 }).toBe('harvestable');
  await page.addInitScript(token => localStorage.setItem('auth_token', token), viewer.token);
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
  await page.goto('/');
  await expect(page.locator('html')).toHaveClass(/dark/);
  const card = page.getByRole('button', { name: 'Open garden Shared Patch', exact: true });
  await expect(card).toContainText('1 ready to harvest');
  await card.focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('region', { name: 'Garden plots', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Harvest plant', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Remove plant', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Plant seed in position 2', exact: true })).toBeDisabled();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')).toBe(true);
  await page.screenshot({ path: test.info().outputPath('shared-garden-view-only.png'), fullPage: true });
  const changed = await request.put(`${base}/garden-shares/garden/${garden.id}/permissions`, { headers, data: { user_id: viewer.user.id, permissions: ['plant', 'harvest'] } });
  expect(changed.ok()).toBe(true);
  await expect(page.getByRole('button', { name: 'Harvest plant', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Plant seed in position 2', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: 'Remove plant', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Harvest plant', exact: true }).click();
  await expect(page.getByText(/went to the player who grew it/)).toBeVisible();
});
